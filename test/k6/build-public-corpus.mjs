import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const manifest = JSON.parse(await readFile(join(here, 'manifest.json'), 'utf8'));
const output = resolve(process.env.ACOUSTICALC_K6_OUTPUT ?? join(here, 'generated'));
const audioDirectory = join(output, 'audio');

try {
  execFileSync('ffmpeg', ['-version'], { stdio: 'ignore' });
} catch {
  console.error('K6: falta ffmpeg en PATH; es necesario para decodificar los previews a mono 44,1 kHz.');
  process.exit(1);
}

await mkdir(audioDirectory, { recursive: true });
const failures = [];
for (const track of manifest) {
  const label = `${track.artist} - ${track.title}`;
  try {
    const detail = await fetch(`https://api.deezer.com/track/${track.deezerId}`).then((response) => response.json());
    if (!detail.preview) throw new Error('Deezer no devolvió preview para este track');
    const mp3 = join(output, `${track.deezerId}.mp3`);
    const f32 = join(audioDirectory, `${track.deezerId}.f32`);
    if (!existsSync(mp3)) {
      const response = await fetch(detail.preview);
      if (!response.ok) throw new Error(`descarga del preview: HTTP ${response.status}`);
      await writeFile(mp3, Buffer.from(await response.arrayBuffer()));
    }
    if (!existsSync(f32)) {
      execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', mp3, '-ac', '1', '-ar', '44100', '-f', 'f32le', f32]);
    }
    const pcm = await readFile(f32);
    if (pcm.byteLength === 0) throw new Error('el f32 decodificado está vacío');
    const seconds = pcm.byteLength / 4 / 44_100;
    if (seconds < 20) throw new Error(`el preview decodificado dura sólo ${seconds.toFixed(2)} s`);
    console.log(`K6: ${label}: ${seconds.toFixed(2)} s (${(pcm.byteLength / 1024 / 1024).toFixed(1)} MiB)`);
  } catch (error) {
    failures.push(`${label}: ${error instanceof Error ? error.message : String(error)}`);
  }
}

if (failures.length) {
  console.error(`K6: no se pudo construir el corpus (${failures.length} fallo(s)):\n- ${failures.join('\n- ')}`);
  process.exit(1);
}

const source = `// Generated by test/k6/build-public-corpus.mjs. Do not commit this file or its audio.
import { readFileSync } from 'node:fs';

const audio = (id) => {
  const buffer = readFileSync(new URL(\`./audio/\${id}.f32\`, import.meta.url));
  return new Float32Array(buffer.buffer, buffer.byteOffset, buffer.length / 4);
};

export default [
${manifest.map((track) => `  { pcm: audio(${track.deezerId}), key: ${JSON.stringify(track.key)}, bpm: ${track.bpm} },`).join('\n')}
];
`;
await writeFile(join(output, 'corpus.mjs'), source);
console.log(`K6: corpus escrito en ${join(output, 'corpus.mjs')}`);
console.log('K6: ejecuta ACOUSTICALC_K6_CORPUS_MODULE=' + join(output, 'corpus.mjs') + ' npm run test:k6');
